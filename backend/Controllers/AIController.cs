    private static List<SampleTicketSpecification> ParseSampleTicketSpecifications(string rawResult)
    {
        var start = rawResult.IndexOf('{');
        var end = rawResult.LastIndexOf('}');
        if (start < 0 || end <= start)
        {
            return [];
        }

        try
        {
            var payload = JsonSerializer.Deserialize<SampleTicketPayload>(
                rawResult[start..(end + 1)],
                new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return payload?.Tickets
                .Where(ticket => !string.IsNullOrWhiteSpace(ticket.Title)
                    && !string.IsNullOrWhiteSpace(ticket.Description))
                .ToList() ?? [];
        }
        catch (JsonException)
        {
            return [];
        }
    }

    private static RecommendationPayload? ParseRecommendation(string rawResult)
    {
        var start = rawResult.IndexOf('{');
        var end = rawResult.LastIndexOf('}');
        if (start < 0 || end <= start)
        {
            return null;
        }

        try
        {
            return JsonSerializer.Deserialize<RecommendationPayload>(
                rawResult[start..(end + 1)],
                new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
        }
        catch (JsonException)
        {
            return null;
        }
    }

    private static RecommendationOption? FindOption(
        string? name,
        List<RecommendationOption> options)
    {
        return string.IsNullOrWhiteSpace(name)
            ? null
            : options.FirstOrDefault(option => string.Equals(
                option.Name,
                name.Trim(),
                StringComparison.OrdinalIgnoreCase));
    }

    private static RecommendationOption FindRecommendedOption(
        string recommendationType,
        AIRecommendationRequestDto request,
        List<RecommendationOption> options)
    {
        var recommendation = GenerateDemoRecommendation(recommendationType, request, options);
        return options.First(option => option.Id == recommendation.RecommendedId);
    }

    private static bool ContainsAny(string value, params string[] terms)
    {
        return terms.Any(value.Contains);
    }

    private static string Truncate(string value, int maxLength)
    {
        return value.Length <= maxLength ? value : value[..maxLength];
    }

